#!/usr/bin/env python3
"""Design the prototype filter of the 32/27 oversampled coarse filter bank and
write the constants used by hw/hdl/ospfb.vhd and the bit-exact model.

    uv run --no-project --with numpy --with scipy hw/scripts/gen_ospfb_coefs.py

Outputs (both tracked in git, regenerate only to change the filter):
    hw/hdl/ospfb_pkg.vhd      coefficients, DFT and rotation tables (VHDL)
    hw/sim/ospfb_coefs.json   the same numbers for hw/sim/ospfb_model.py

Filter bank: M = 32 real-input branches, decimation D = 27 (oversampling
32/27), T = 16 taps per branch (L = 512).  Coarse channel k is centred on
k * fs/32 = k * 122.88 MHz and sampled at fs/27 = 145.636 MS/s complex, so
energy at |f| > fs/27 - fs/64 = 84.20 MHz from the centre aliases into the
channel's nominal band |f| < fs/64 = 61.44 MHz.  The prototype is an
equiripple low-pass, flat to PASS_HZ, with its stopband from 84.20 MHz.

Fixed point (same scaling as the CSIRO pfb32x16t + rnd_23_18 it replaces):
    coefficients  18 bit, peak +131071
    branch sums   v = round(sum(c * code) / 2**11), 18 bit (64 * code at DC
                  for a filter with unity gain)
    DFT twiddles  18 bit, 1.0 = 2**16
    rotation      e^{-j 2 pi q/32} / G, 18 bit, 1.0 = 2**16, where G is the
                  DC gain of the quantised filter relative to unity: it makes
                  the output scale independent of the coefficient scaling
    output        round(DFT(v) / 32) after rotation, 18 bit
"""
import json
import os

import numpy as np
from scipy import signal

FS = 3932.16e6
M, D, T = 32, 27, 16
L = M * T
PASS_HZ = 58.0e6                    # flat (< 0.01 dB ripple) to here
STOP_HZ = FS / D - FS / (2 * M)     # 84.196 MHz: aliases onto the band edge
STOP_WEIGHT = 10.0
CBITS = 18                          # coefficient width
TW_ONE = 1 << 16                    # 1.0 in the twiddle tables

HERE = os.path.dirname(os.path.abspath(__file__))
HW = os.path.dirname(HERE)


def design():
    h = signal.remez(L, [0, PASS_HZ, STOP_HZ, FS / 2], [1, 0],
                     weight=[1, STOP_WEIGHT], fs=FS, maxiter=200)
    c = np.round(h / np.max(np.abs(h)) * ((1 << (CBITS - 1)) - 1)).astype(np.int64)
    assert np.array_equal(c, c[::-1]), "prototype must be symmetric"
    # DC gain of a branch relative to unity (sum of c over a branch = 2**17)
    gain = c.sum() / (M * (1 << (CBITS - 1)))
    return c, gain


def response(c):
    n = 1 << 19
    H = np.abs(np.fft.rfft(c / c.sum(), n))
    f = np.arange(len(H)) * FS / n
    db = 20 * np.log10(H + 1e-15)
    return f, db


def tables(gain):
    q = np.arange(M)
    cos_t = np.round(np.cos(2 * np.pi * q / M) * TW_ONE).astype(int)
    sin_t = np.round(np.sin(2 * np.pi * q / M) * TW_ONE).astype(int)
    rot_c = np.round(np.cos(2 * np.pi * q / M) / gain * TW_ONE).astype(int)
    rot_s = np.round(np.sin(2 * np.pi * q / M) / gain * TW_ONE).astype(int)
    lim = 1 << (CBITS - 1)
    for t in (cos_t, sin_t, rot_c, rot_s):
        assert t.max() < lim and t.min() >= -lim
    return cos_t, sin_t, rot_c, rot_s


def vhdl_list(v, per_line=8, indent="    "):
    s = [f"{int(x):7d}" for x in v]
    lines = [", ".join(s[i:i + per_line]) for i in range(0, len(s), per_line)]
    return (",\n" + indent).join(lines)


def main():
    c, gain = design()
    f, db = response(c)
    at = lambda hz: db[np.searchsorted(f, hz)]   # noqa: E731
    band = FS / (2 * M)
    pb = db[f <= PASS_HZ]
    alias = db[f >= STOP_HZ].max()
    summary = [
        f"taps {L} ({M} x {T}), 18-bit, peak {c.max()}, DC gain G = {gain:.6f}",
        f"passband 0-{PASS_HZ / 1e6:.1f} MHz ripple {pb.max() - pb.min():.4f} dB",
        f"response at the band edge {band / 1e6:.2f} MHz: {at(band):.2f} dB",
        f"stopband from {STOP_HZ / 1e6:.3f} MHz: <= {alias:.1f} dB "
        f"(alias rejection inside +-{band / 1e6:.2f} MHz)",
        f"-3 dB at {f[np.argmax(db < -3)] / 1e6:.2f} MHz, -6 dB at {f[np.argmax(db < -6)] / 1e6:.2f} MHz",
    ]
    for s in summary:
        print(s)
    cos_t, sin_t, rot_c, rot_s = tables(gain)

    pkg = f"""-------------------------------------------------------------------------------
-- ospfb_pkg : constants of the 32/27 oversampled coarse filter bank (ospfb)
--
-- GENERATED by hw/scripts/gen_ospfb_coefs.py - do not edit by hand.
--
-- Prototype low-pass: {L} taps ({M} branches x {T}), equiripple (Remez),
-- flat to {PASS_HZ / 1e6:.1f} MHz, stopband from {STOP_HZ / 1e6:.3f} MHz = fs/27 - fs/64
-- at fs = 3932.16 MS/s.
""" + "".join(f"--   {s}\n" for s in summary) + f"""--
-- COEF(l), l = p + 32*t : tap t of branch p (sample x[n - l]), 18 bit.
-- TW_COS/TW_SIN(q)      : cos/sin(2 pi q/32), 1.0 = 2**16 (DFT twiddles).
-- ROT_COS/ROT_SIN(q)    : cos/sin(2 pi q/32) / G, 1.0 = 2**16 (rotation and
--                         gain correction, G = DC gain of COEF / 2**17).
-------------------------------------------------------------------------------
package ospfb_pkg is

  constant OS_M    : integer := {M};     -- branches = coarse channel spacing fs/M
  constant OS_D    : integer := {D};     -- decimation: output rate fs/D
  constant OS_T    : integer := {T};     -- taps per branch

  type int_arr_t is array (natural range <>) of integer;

  constant COEF : int_arr_t(0 to {L - 1}) := (
    {vhdl_list(c)}
  );

  constant TW_COS : int_arr_t(0 to {M - 1}) := (
    {vhdl_list(cos_t)}
  );
  constant TW_SIN : int_arr_t(0 to {M - 1}) := (
    {vhdl_list(sin_t)}
  );
  constant ROT_COS : int_arr_t(0 to {M - 1}) := (
    {vhdl_list(rot_c)}
  );
  constant ROT_SIN : int_arr_t(0 to {M - 1}) := (
    {vhdl_list(rot_s)}
  );

end package ospfb_pkg;
"""
    with open(os.path.join(HW, "hdl", "ospfb_pkg.vhd"), "w") as fh:
        fh.write(pkg)
    with open(os.path.join(HW, "sim", "ospfb_coefs.json"), "w") as fh:
        json.dump({"M": M, "D": D, "T": T, "fs": FS, "pass_hz": PASS_HZ, "stop_hz": STOP_HZ,
                   "gain": gain, "coef": c.tolist(), "tw_cos": cos_t.tolist(),
                   "tw_sin": sin_t.tolist(), "rot_cos": rot_c.tolist(),
                   "rot_sin": rot_s.tolist(), "summary": summary}, fh, indent=1)
    print("wrote hw/hdl/ospfb_pkg.vhd and hw/sim/ospfb_coefs.json")


if __name__ == "__main__":
    main()
